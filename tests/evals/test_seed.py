SCREENING_SYMBOLS = [
    "ANET",
    "AVGO",
    "CVS",
    "INTC",
    "META",
    "NFLX",
    "NKE",
    "NVDA",
    "PLTR",
]


def _read(path: Path) -> dict[str, object]:
    engine = create_engine_from_settings(DatabaseSettings(url=f"sqlite:///{path}"))
    try:
        with session_scope(sessionmaker(bind=engine)) as session:

            def count(table: Table) -> int:
                return session.execute(select(func.count()).select_from(table)).one()[0]

            return {
                "symbols": list_symbols(session),
                "screening_rows": count(SCR_RESULTS),
                "positions": count(PF_POSITIONS),
                "watchlist_items": count(WATCHLIST_ITEMS),
                "journal_trades": count(JOURNAL_ENTRIES),
            }
    finally:
        engine.dispose()


def test_empty_state_has_no_rows(tmp_path: Path) -> None:
    state = _read(seed.build("empty", tmp_path / "empty.db"))

    assert state == {
        "symbols": [],
        "screening_rows": 0,
        "positions": 0,
        "watchlist_items": 0,
        "journal_trades": 0,
    }


@pytest.mark.parametrize("data_state", ["seeded", "edge"])
def test_seeded_states_register_a_universe_instead_of_a_snapshot(
    tmp_path: Path, data_state: str
) -> None:
    state = _read(seed.build(data_state, tmp_path / f"{data_state}.db"))

    assert state == {
        "symbols": SCREENING_SYMBOLS,
        "screening_rows": 0,
        "positions": 5,
        "watchlist_items": 3,
        "journal_trades": 4,
    }


@pytest.mark.parametrize("state", ["seeded", "edge"])
def test_every_financial_fixture_declares_synthetic_basis_and_decimal_arithmetic(
    tmp_path, state
):
    path = seed.build(state, tmp_path / f"{state}.db")
    engine = create_engine_from_settings(DatabaseSettings(url=f"sqlite:///{path}"))
    try:
        with session_scope(sessionmaker(bind=engine)) as session:
            positions = session.execute(select(PF_POSITIONS)).mappings().all()
            for position, fixture in zip(
                sorted(positions, key=lambda row: row["ticker"]),
                sorted(seed.POSITIONS),
                strict=True,
            ):
                symbol, shares, price, bought, _ = fixture
                assert "synthetic" in position["notes"].lower()
                assert seed.FIXTURE_VERSION in position["notes"]
                assert position["purchase_date"].date().isoformat() == bought
                assert position["total_cost"] == (
                    Decimal(shares) * Decimal(price)
                ).quantize(Decimal("0.01"))
            nvda = next(row for row in positions if row["ticker"] == "NVDA")
            assert nvda["total_cost"] == Decimal("21600.60")
            trades = (
                session.execute(select(JOURNAL_ENTRIES).order_by(JOURNAL_ENTRIES.c.id))
                .mappings()
                .all()
            )
            for trade, fixture in zip(trades, seed.TRADES, strict=True):
                symbol, price, shares, entered, tag, rationale, closed = fixture
                assert "synthetic" in trade["rationale"].lower()
                assert seed.FIXTURE_VERSION in trade["rationale"]
                assert Decimal(str(trade["entry_price"])) == Decimal(price)
                assert trade["entry_date"].date().isoformat() == entered
                if closed:
                    expected = (
                        (Decimal(closed[0]) - Decimal(price)) * Decimal(shares)
                    ).quantize(Decimal("0.01"))
                    assert Decimal(str(trade["pnl"])) == expected == Decimal("50.50")
                    assert trade["exit_date"].date().isoformat() == closed[1]
    finally:
        engine.dispose()


def test_repeat_builds_have_equivalent_business_contents(tmp_path):
    import sqlite3

    def contents(path):
        with sqlite3.connect(path) as conn:
            rows = {}
            for (name,) in conn.execute(
                "SELECT name FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%' ORDER BY name"
            ):
                columns = [
                    row[1] for row in conn.execute(f'PRAGMA table_info("{name}")')
                ]
                # UUID identity and audit timestamps are generated by domain APIs.
                included = [
                    column
                    for column in columns
                    if column
                    not in {
                        "id",
                        "portfolio_id",
                        "created_at",
                        "updated_at",
                        "added_at",
                    }
                ]
                if included:
                    fields = ", ".join(f'"{column}"' for column in included)
                    rows[name] = sorted(
                        conn.execute(f'SELECT {fields} FROM "{name}"').fetchall(),
                        key=repr,
                    )
            return rows

    first, second = (
        seed.build_all(tmp_path / "first"),
        seed.build_all(tmp_path / "second"),
    )
    for state in seed.STATES:
        assert contents(first[state]) == contents(second[state])


